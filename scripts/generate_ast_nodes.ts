// Generates `src/ast/generated.rs`, which converts references to oxc's ast
// structs and enums to a `Node` (oxc's `AstKind`).
//
// Run this after upgrading oxc:
//   deno run -A scripts/generate_ast_nodes.ts <path to oxc_ast crate>
//
// The oxc_ast crate is found in the cargo registry (ex. `~/.cargo/registry/src/*/oxc_ast-x.y.z`).

const oxcAstDir = Deno.args[0];
if (oxcAstDir == null) {
  console.error("Usage: deno run -A scripts/generate_ast_nodes.ts <path to oxc_ast crate>");
  Deno.exit(1);
}

const kindTypes = getAstKindTypes();
const enums = getEnums();
const output = generate();
const outputPath = new URL("../src/ast/generated.rs", import.meta.url);
Deno.writeTextFileSync(outputPath, output);
console.log(`Wrote ${outputPath.pathname}`);

interface EnumVariant {
  name: string;
  typeName: string;
}

interface EnumDef {
  name: string;
  hasLifetime: boolean;
  variants: EnumVariant[];
  inherits: string[];
}

function generate() {
  const lines: string[] = [];
  lines.push("// Auto-generated by scripts/generate_ast_nodes.ts. Do not edit directly.");
  lines.push("");
  lines.push("use oxc_ast::AstKind;");
  lines.push("use oxc_ast::ast::*;");
  lines.push("");
  lines.push("use oxc_span::GetSpan;");
  lines.push("");
  lines.push("use super::IntoNode;");
  lines.push("use super::SourcePos;");
  lines.push("use super::SourceRanged;");
  lines.push("");

  // structs
  for (const [variantName, kindType] of kindTypes) {
    const typeText = kindType.hasLifetime ? `${kindType.name}<'a>` : kindType.name;
    lines.push(`impl<'a> IntoNode<'a> for &'a ${typeText} {`);
    lines.push("  #[inline]");
    lines.push("  fn into_node(self) -> AstKind<'a> {");
    lines.push(`    AstKind::${variantName}(self)`);
    lines.push("  }");
    lines.push("}");
    lines.push("");
    pushSourceRanged(kindType.hasLifetime ? `${kindType.name}<'_>` : kindType.name);
  }

  // enums
  const structNames = new Set([...kindTypes.values()].map((t) => t.name));
  const supportedEnums = new Set<string>();
  // resolve until no change because an enum may contain other enums
  let changed = true;
  while (changed) {
    changed = false;
    for (const enumDef of enums.values()) {
      if (supportedEnums.has(enumDef.name)) {
        continue;
      }
      const variants = expandVariants(enumDef);
      if (variants != null && variants.every((v) => structNames.has(v.typeName) || supportedEnums.has(v.typeName))) {
        supportedEnums.add(enumDef.name);
        changed = true;
      }
    }
  }

  for (const enumDef of [...enums.values()].sort((a, b) => a.name.localeCompare(b.name))) {
    if (!supportedEnums.has(enumDef.name)) {
      console.log(`Skipping enum ${enumDef.name}`);
      continue;
    }
    const typeText = enumDef.hasLifetime ? `${enumDef.name}<'a>` : enumDef.name;
    lines.push(`impl<'a> IntoNode<'a> for &'a ${typeText} {`);
    lines.push("  fn into_node(self) -> AstKind<'a> {");
    lines.push("    match self {");
    for (const variant of expandVariants(enumDef)!) {
      lines.push(`      ${enumDef.name}::${variant.name}(it) => it.into_node(),`);
    }
    lines.push("    }");
    lines.push("  }");
    lines.push("}");
    lines.push("");
    pushSourceRanged(enumDef.hasLifetime ? `${enumDef.name}<'_>` : enumDef.name);
  }

  return lines.join("\n");

  function pushSourceRanged(typeText: string) {
    lines.push(`impl SourceRanged for ${typeText} {`);
    lines.push("  #[inline]");
    lines.push("  fn start(&self) -> SourcePos {");
    lines.push("    SourcePos::new(GetSpan::span(self).start)");
    lines.push("  }");
    lines.push("");
    lines.push("  #[inline]");
    lines.push("  fn end(&self) -> SourcePos {");
    lines.push("    SourcePos::new(GetSpan::span(self).end)");
    lines.push("  }");
    lines.push("}");
    lines.push("");
  }
}

function expandVariants(enumDef: EnumDef): EnumVariant[] | undefined {
  const variants = [...enumDef.variants];
  for (const inherited of enumDef.inherits) {
    const inheritedDef = enums.get(inherited);
    if (inheritedDef == null) {
      return undefined;
    }
    const inheritedVariants = expandVariants(inheritedDef);
    if (inheritedVariants == null) {
      return undefined;
    }
    variants.push(...inheritedVariants);
  }
  return variants;
}

function getAstKindTypes() {
  const text = Deno.readTextFileSync(`${oxcAstDir}/src/generated/ast_kind.rs`);
  const start = text.indexOf("pub enum AstKind<'a> {");
  const end = text.indexOf("\n}", start);
  const body = text.slice(start, end);
  const types = new Map<string, { name: string; hasLifetime: boolean }>();
  for (const match of body.matchAll(/^\s+(\w+)\(&'a (\w+)(<'a>)?\)/gm)) {
    types.set(match[1], { name: match[2], hasLifetime: match[3] != null });
  }
  return types;
}

function getEnums() {
  const enums = new Map<string, EnumDef>();
  for (const fileName of ["js.rs", "jsx.rs", "literal.rs", "ts.rs", "comment.rs"]) {
    const text = Deno.readTextFileSync(`${oxcAstDir}/src/ast/${fileName}`);
    for (const match of text.matchAll(/^pub enum (\w+)(<'a>)? \{\n([\s\S]*?)\n\}/gm)) {
      const enumDef: EnumDef = {
        name: match[1],
        hasLifetime: match[2] != null,
        variants: [],
        inherits: [],
      };
      for (const line of match[3].split("\n")) {
        const trimmed = line.trim();
        if (trimmed.startsWith("//") || trimmed.startsWith("#")) {
          continue;
        }
        const inheritMatch = /^INHERIT\((\w+)(<'a>)?\)/.exec(trimmed);
        if (inheritMatch != null) {
          enumDef.inherits.push(inheritMatch[1]);
          continue;
        }
        const variantMatch = /^(\w+)\((.+)\)\s*(=\s*\d+)?,$/.exec(trimmed);
        if (variantMatch != null) {
          enumDef.variants.push({
            name: variantMatch[1],
            typeName: getInnerTypeName(variantMatch[2]),
          });
        } else if (/^\w+(\s*=\s*\d+)?,$/.test(trimmed)) {
          // fieldless variant, so this enum isn't a node
          enumDef.variants.push({ name: trimmed, typeName: "<fieldless>" });
        }
      }
      enums.set(enumDef.name, enumDef);
    }
  }
  return enums;
}

function getInnerTypeName(payload: string) {
  const boxMatch = /^Box<'a, (\w+)/.exec(payload);
  if (boxMatch != null) {
    return boxMatch[1];
  }
  return /^(\w+)/.exec(payload)![1];
}
